# -*- coding: utf-8 -*-
"""
Build a single-file distribution of the tool (like the original one-file Tcl macro).

    python build_onefile.py  ->  hm_screenshot_tool_onefile.py

The generated script embeds every module of the ``hm_shots`` package as source
text and installs an import hook, so it behaves exactly like the package but can
be copied around / run from HyperMesh as ONE .py file.
"""
from __future__ import annotations

import base64
import os
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "hm_shots")
OUT = os.path.join(HERE, "hm_screenshot_tool_onefile.py")

TEMPLATE = '''# -*- coding: utf-8 -*-
"""
HyperMesh Auto-Screenshot & Quality Reporting Tool - SINGLE-FILE build.
Generated by build_onefile.py from the hm_shots package (version %(version)s).

Inside HyperMesh:   File > Run > Python script ...  -> choose this file
Standalone / demo:  python hm_screenshot_tool_onefile.py --demo
"""
import base64 as _b64
import importlib.abc as _abc
import importlib.machinery as _mach
import importlib.util as _util
import sys as _sys
import zlib as _zlib

_SOURCES = _b64.b64decode(%(blob)r)
_MODULES = eval(_zlib.decompress(_SOURCES).decode("utf-8"))   # {module_name: source}


class _EmbeddedFinder(_abc.MetaPathFinder, _abc.Loader):
    def find_spec(self, name, path=None, target=None):
        if name in _MODULES:
            is_pkg = name == "hm_shots" or name.endswith(".gui") or name.endswith(".tests")
            spec = _mach.ModuleSpec(name, self, is_package=is_pkg, origin="embedded:" + name)
            if is_pkg:
                spec.submodule_search_locations = []
            return spec
        return None

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        src = _MODULES[module.__name__]
        module.__file__ = "embedded:" + module.__name__
        code = compile(src, module.__file__, "exec")
        exec(code, module.__dict__)


if "hm_shots" not in _sys.modules:
    _sys.meta_path.insert(0, _EmbeddedFinder())

from hm_shots.gui.app import run  # noqa: E402

window = run((getattr(_sys, "argv", None) or [])[1:])
'''


def collect() -> dict:
    mods = {}
    for root, _dirs, files in os.walk(PKG):
        if "__pycache__" in root or os.path.basename(root) == "tests":
            continue
        for f in sorted(files):
            if not f.endswith(".py"):
                continue
            rel = os.path.relpath(os.path.join(root, f), HERE)
            name = rel[:-3].replace(os.sep, ".")
            if name.endswith(".__init__"):
                name = name[: -len(".__init__")]
            with open(os.path.join(root, f), "r", encoding="utf-8") as fh:
                mods[name] = fh.read()
    return mods


def main() -> None:
    mods = collect()
    version = "?"
    for line in mods["hm_shots"].splitlines():
        if line.startswith("__version__"):
            version = line.split("=", 1)[1].strip().strip('"')
    blob = base64.b64encode(zlib.compress(repr(mods).encode("utf-8"), 9)).decode("ascii")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(TEMPLATE % {"blob": blob, "version": version})
    print("wrote %s (%d modules, %d KB)" % (OUT, len(mods), os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    main()
